static const char *lookup(char c)
{
    for (size_t i = 0; i < sizeof(s_font) / sizeof(s_font[0]); i++) {
        if (s_font[i].c == c) {
            return s_font[i].rows;
        }
    }
    return NULL;
}

int ui_text_width(const char *s, int scale)
{
    int n = (int)strlen(s);
    if (n <= 0) {
        return 0;
    }
    return n * 6 * scale - scale;   // 字宽 5 + 字距 1
}

void ui_text_draw(uint16_t *fb, int fb_w, int fb_h, int x, int y,
                  const char *s, uint16_t px, int scale)
{
    if (!fb || !s || scale <= 0) {
        return;
    }
    int cx = x;
    for (const char *p = s; *p; p++) {
        char c = (*p >= 'a' && *p <= 'z') ? (char)(*p - 'a' + 'A') : *p;
        const char *rows = (c == ' ') ? NULL : lookup(c);
        if (rows) {
            for (int row = 0; row < 7; row++) {
                for (int col = 0; col < 5; col++) {
                    if (rows[row * 5 + col] != '1') {
                        continue;
                    }
                    for (int dy = 0; dy < scale; dy++) {
                        int py = y + row * scale + dy;
                        if (py < 0 || py >= fb_h) {
                            continue;
                        }
                        for (int dx = 0; dx < scale; dx++) {
                            int pxx = cx + col * scale + dx;
                            if (pxx < 0 || pxx >= fb_w) {
                                continue;
                            }
                            fb[py * fb_w + pxx] = px;
                        }
                    }
                }
            }
        }
        cx += 6 * scale;
    }
}
